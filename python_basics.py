# Python Basics Practice

# Variables
name = "Susmitha"
age = 19

print("Name:", name)
print("Age:", age)

# Basic arithmetic
a = 10
b = 5

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)

# Conditional statement
if age >= 18:
    print("Adult")
else:
    print("Minor")

# Loop
for i in range(1, 6):
    print(i)
